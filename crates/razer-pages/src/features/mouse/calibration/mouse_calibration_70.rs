    pub(super) fn calibration_surface_rows(
        &self,
        window: &mut Window,
        cx: &mut Context<Self>,
    ) -> AnyElement {
        let smart_preset = calibration_preset::supports(self.spec.product_id);
        let default = [json!({"surfaceId":"default","type":"default"})];
        let profiles = self
            .draft
            .pointer("/calibration/profiles")
            .and_then(Value::as_array)
            .map(Vec::as_slice)
            .unwrap_or(&default);
        let selected = self.draft.pointer("/calibration/selectedProfile/guid");
        let selected_index = profiles
            .iter()
            .position(|profile| profile.get("guid") == selected)
            .unwrap_or(0);
        let mut order: Vec<usize> = (0..profiles.len()).collect();
        if self.spec.product_id != 185 {
            order.sort_by(|a, b| {
                let a_default = profiles[*a]["type"] == "default";
                let b_default = profiles[*b]["type"] == "default";
                b_default.cmp(&a_default).then_with(|| {
                    let a = profiles[*a]["calibrationDate"]
                        .as_str()
                        .and_then(|value| calibration_date_order(self.spec.product_id, value));
                    let b = profiles[*b]["calibrationDate"]
                        .as_str()
                        .and_then(|value| calibration_date_order(self.spec.product_id, value));
                    match (a, b) {
                        (Some(a), Some(b)) => a.cmp(&b),
                        _ => std::cmp::Ordering::Equal,
                    }
                })
            });
        }
        let enabled = self.calibration_state.feature_access != "NONE";
        let mut surfaces = h_flex()
            .flex_wrap()
            .items_start()
            .gap(surface::css(20.))
            .children(order.into_iter().enumerate().map(|(display_index, index)| {
                let profile = &profiles[index];
                let guid = profile.get("guid").cloned();
                let is_default = if smart_preset && self.spec.product_id != 185 {
                    profile["name"] == "default"
                } else {
                    profile["type"] == "default"
                };
                // nR intentionally derives n before sorting the display copy;
                // PS reports its displayed idx back to the original profiles.
                let active = selected_index == display_index;
                let selection_guid = profiles[display_index].get("guid").cloned();
                let mat = artwork(
                    self.spec.product_id,
                    profile["surfaceId"].as_str().unwrap_or("default"),
                );
                // nR resolves preset names and editions from $S, not the
                // persisted name (which may belong to a different locale).
                let name = if profile["type"] == "custom" {
                    let name = profile["name"].as_str().unwrap_or_default();
                    if self.spec.product_id == 162 {
                        t(name).to_string()
                    } else {
                        name.to_owned()
                    }
                } else {
                    t(&mat.name).to_string()
                };
                let identity = guid.as_ref().and_then(Value::as_str).unwrap_or("default");
                let menu_guid = guid.as_ref().and_then(Value::as_str).map(str::to_owned);
                let menu_name = name.clone();
                let custom = profile["type"] == "custom";
                let hover = if self.spec.product_id == 162 {
                    motion::card_hover(
                        display_index,
                        enabled
                            && self.calibration_state.babel_surface_hover == Some(display_index),
                        window,
                        cx,
                    )
                } else {
                    0.
                };
                let card = BaseButton::new(SharedString::from(format!(
                    "mouse-70-calibration-profile-{identity}"
                )))
                .accessibility_label(name.clone())
                .selected(active)
                .disabled(!enabled)
                .opacity(if enabled { 1. } else { 0.3 })
                .relative()
                .w(surface::css(290.))
                .h(surface::css(200.))
                .px(surface::css(20.))
                .py(surface::css(8.))
                .rounded(surface::css(5.))
                .bg(cx.theme().group_box)
                .hover(|style| style.text_color(cx.theme().primary))
                .focus_visible(|style| style.text_color(cx.theme().primary))
                .child(
                    div()
                        .absolute()
                        .top(surface::css(10.))
                        .left(surface::css(10.))
                        .size(surface::css(20.))
                        .rounded(surface::css(10.))
                        .child(motion::selected_check(
                            self.spec.product_id,
                            display_index,
                            active,
                            window,
                            cx,
                        )),
                )
                .child(
                    img(SharedString::from(mat.image.clone()))
                        .w(surface::css(250.))
                        .h(surface::css(140.))
                        .object_fit(ObjectFit::Contain),
                )
                .child(
                    div()
                        .text_center()
                        .text_size(surface::css(14.))
                        .line_height(surface::css(16.))
                        .when(self.spec.product_id == 162, |text| {
                            text.text_color(motion::hover_color(0xcccccc, hover))
                        })
                        .child(name.to_uppercase()),
                )
                .children(is_default.then(|| {
                    div()
                        .text_center()
                        .text_size(surface::css(12.))
                        .text_color(DrawerColors::new().muted())
                        .when(self.spec.product_id == 162, |text| {
                            text.text_color(motion::hover_color(0x707070, hover))
                        })
                        .child(t("NO_CALIBRATION"))
                }))
                .children(
                    (profile["type"] == "preset" && !mat.edition.is_empty()).then(|| {
                        div()
                            .text_center()
                            .text_size(surface::css(12.))
                            .text_color(DrawerColors::new().muted())
                            .when(self.spec.product_id == 162, |text| {
                                text.text_color(motion::hover_color(0x707070, hover))
                            })
                            .child(t(&mat.edition).to_uppercase())
                    }),
                )
                .children((profile["type"] == "custom").then(|| {
                    div()
                        .text_center()
                        .text_size(surface::css(12.))
                        .text_color(DrawerColors::new().muted())
                        .when(self.spec.product_id == 162, |text| {
                            text.text_color(motion::hover_color(0x707070, hover))
                        })
                        .child(format!(
                            "{}{}",
                            if self.spec.product_id == 162 {
                                "Calibrated: ".to_owned()
                            } else {
                                t("CALIBRATED").to_string()
                            },
                            profile["calibrationDate"].as_str().unwrap_or_default()
                        ))
                }))
                .on_click(cx.listener(move |this, _, window, cx| {
                    if smart_preset {
                        this.select_preset_calibration(selection_guid.clone(), window, cx);
                    } else {
                        this.select_calibration(selection_guid.clone(), cx);
                    }
                }));
                div()
                    .id(SharedString::from(format!(
                        "mouse-calibration-surface-{display_index}"
                    )))
                    .relative()
                    .w(surface::css(290.))
                    .h(surface::css(200.))
                    .flex_shrink_0()
                    .when(enabled && self.spec.product_id != 162, |surface| {
                        surface.hover(|style| style.top(surface::css(-4.)))
                    })
                    .when(self.spec.product_id == 162, |view| {
                        view.top(surface::css(-4. * hover)).on_hover(cx.listener(
                            move |this, inside: &bool, _, cx| {
                                if *inside {
                                    this.calibration_state.babel_surface_hover =
                                        Some(display_index);
                                } else if this.calibration_state.babel_surface_hover
                                    == Some(display_index)
                                {
                                    this.calibration_state.babel_surface_hover = None;
                                }
                                cx.notify();
                            },
                        ))
                    })
                    .child(card)
                    .children(
                        menu_guid
                            .filter(|_| !is_default)
                            .map(|guid| self.calibration_menu(guid, menu_name, custom, cx)),
                    )
            }));
        let show_add = smart_preset || self.calibration_state.show_add;
        if show_add {
            surfaces = surfaces.child(
                BaseButton::new("mouse-calibration-add-surface")
                    .flex_shrink_0()
                    .accessibility_label(t("ADD_A_SURFACE"))
                    .w(surface::css(290.))
                    .h(surface::css(200.))
                    .rounded(surface::css(5.))
                    .border_2()
                    .border_dashed()
                    .border_color(cx.theme().border)
                    .hover(|style| style.border_color(cx.theme().primary))
                    .flex()
                    .flex_col()
                    .items_center()
                    .justify_start()
                    .pt(surface::css(8.))
                    .child(
                        img(self.calibration_image("icon_add.c95a8d74.svg"))
                            .size(surface::css(40.))
                            .my(surface::css(50.)),
                    )
                    .child(t("ADD_A_SURFACE"))
                    .on_click(cx.listener(|this, _, window, cx| this.open_calibration(window, cx))),
            );
        }
        // nR.adjustCol reserves one 310px column for lift-off controls and
        // counts the add tile as a surface, even with no lift-off panel.
        let unit = f32::from(window.rem_size()) / 16.;
        let columns =
            ((f32::from(window.viewport_size().width) / unit - 20.) / 310.).trunc() as i32 - 1;
        let count = profiles.len() + usize::from(show_add);
        if columns > 0 {
            surfaces = surfaces.max_w(surface::css(310. * columns.min(count as i32) as f32));
        }
        let mut page = h_flex()
            .w_full()
            .items_start()
            .gap(surface::css(20.))
            .child(surfaces);
        // Source nR renders LS only after a second calibration profile exists.
        if profiles.len() > 1 && smart_preset && self.spec.product_id != 185 {
            page = page.child(self.preset_calibration_tracking_panel(window, cx));
        } else if profiles.len() > 1 {
            let is_default = if matches!(self.spec.product_id, 70 | 162) {
                self.calibration_state.babel_lift_using_default
            } else {
                profiles
                    .iter()
                    .find(|profile| profile.get("guid") == selected)
                    .is_none_or(|profile| profile["type"] == "default")
            };
            let value = self.number("/calibration/liftOffRangeValue");
            page = page.child(
                div()
                    .w(surface::css(290.))
                    .flex_shrink_0()
                    .p(surface::css(20.))
                    .bg(rgb(0x111111))
                    .opacity(if enabled { 1. } else { 0.3 })
                    .rounded(surface::css(5.))
                    .child(
                        div()
                            .text_color(rgb(0x44d62c))
                            .text_size(surface::css(16.))
                            .mb(surface::css(20.))
                            .child(t("LIFT_OFF_RANGE_HEADER")),
                    )
                    .child(div().mb(surface::css(10.)).child(t("LIFT_OFF_RANGE_DESC")))
                    .child(
                        div()
                            .relative()
                            .w(surface::css(250.))
                            .h(surface::css(64.))
                            .mb(surface::css(20.))
                            .children(matches!(self.spec.product_id, 162 | 185).then(|| {
                                self.slider_190(
                                    "/calibration/liftOffRangeValue",
                                    "1",
                                    None,
                                    "10",
                                    false,
                                    !is_default && enabled,
                                    cx,
                                )
                            }))
                            .children((!matches!(self.spec.product_id, 162 | 185)).then(|| {
                                SourceSlider::new(
                                    &self.sliders["/calibration/liftOffRangeValue"],
                                    (value - 1.) / 9.,
                                )
                                .enabled(!is_default && enabled)
                                .tip(Some(format!("{value:.0}")))
                            }))
                            .children((!matches!(self.spec.product_id, 162 | 185)).then(|| {
                                div()
                                    .absolute()
                                    .bottom_0()
                                    .w_full()
                                    .child(surface::slider_tags("1", None, "10", None))
                            })),
                    )
                    .child(
                        div()
                            .text_size(surface::css(16.))
                            .mb(surface::css(10.))
                            .child(t("RESET")),
                    )
                    .child(t("RESET_DESC1")),
            );
        }
        page.into_any_element()
    }

