pub(super) fn supports_surface_calibration(product_id: u32) -> bool {
    // /162's Babel jc/zc root is independently audited, outside the /70
    // equivalence receipt. It uses its own images, lift state and start action.
    if product_id == 162 {
        return true;
    }
    static PRODUCTS: OnceLock<Vec<u32>> = OnceLock::new();
    PRODUCTS
        .get_or_init(|| read_mouse_calibration_family_catalog())
        .contains(&product_id)
}

#[derive(Deserialize)]
struct CalibrationArtwork {
    mats: Vec<CalibrationMat>,
    date_formats: BTreeMap<String, Vec<String>>,
    date_parse_patterns: BTreeMap<String, [u32; 2]>,
    #[serde(default)]
    images: BTreeMap<String, String>,
}

#[derive(Deserialize)]
struct CalibrationMat {
    surface_id: String,
    name: String,
    edition: String,
    image: String,
    url: String,
    source_image: String,
}

fn calibration_artwork(product_id: u32) -> &'static CalibrationArtwork {
    if product_id == 162 {
        static BABEL_ARTWORK: OnceLock<CalibrationArtwork> = OnceLock::new();
        return BABEL_ARTWORK.get_or_init(|| read_mouse_calibration_162_catalog());
    }
    static ARTWORK: OnceLock<CalibrationArtwork> = OnceLock::new();
    ARTWORK.get_or_init(|| read_mouse_calibration_70_catalog())
}

fn artwork(product_id: u32, surface_id: &str) -> &'static CalibrationMat {
    calibration_artwork(product_id)
        .mats
        .iter()
        .find(|mat| mat.surface_id == surface_id)
        .unwrap_or_else(|| {
            calibration_artwork(product_id)
                .mats
                .last()
                .expect("source fallback artwork")
        })
}

fn calibration_date(product_id: u32) -> String {
    use chrono::Datelike;
    let today = chrono::Local::now();
    let formats = &calibration_artwork(product_id).date_formats;
    // The current source _R explicitly maps kr to ko-KR and jp to jp.
    // Unknown app language keys follow the app's English fallback.
    let patterns = formats.get(&razer_i18n::locale()).unwrap_or(&formats["en"]);
    patterns[today.month0() as usize]
        .replace("{year}", &today.year().to_string())
        .replace("{day}", &today.day().to_string())
}

fn calibration_date_order(product_id: u32, value: &str) -> Option<chrono::NaiveDate> {
    if let Ok(value) = chrono::NaiveDate::parse_from_str(value, "%Y-%m-%d") {
        return Some(value);
    }
    if let Ok(value) = chrono::DateTime::parse_from_rfc3339(value) {
        return Some(value.date_naive());
    }
    // Persisted dates are generated by the source's Intl formatter. The table
    // preserves V8 Date.parse acceptance and ambiguous numeric ordering rather
    // than sorting localized text or assuming day/month order.
    let bytes = value.as_bytes();
    let start = (0..bytes.len().saturating_sub(3)).find(|&index| {
        bytes[index..index + 4].iter().all(u8::is_ascii_digit)
            && (index == 0 || !bytes[index - 1].is_ascii_digit())
            && (index + 4 == bytes.len() || !bytes[index + 4].is_ascii_digit())
    })?;
    let year = value[start..start + 4].parse().ok()?;
    let mut pattern = value.to_owned();
    pattern.replace_range(start..start + 4, "{year}");
    let [month, day] = *calibration_artwork(product_id)
        .date_parse_patterns
        .get(&pattern)?;
    chrono::NaiveDate::from_ymd_opt(year, month, day)
}

