//! Dashboard module 46114 Rk preserves the mounted recorder's key order and fields.
use serde::Deserialize;
use std::sync::OnceLock;

#[derive(Debug, Deserialize)]
pub(super) struct CaptureKey {
    pub(super) name: String,
    #[serde(rename = "inputID")]
    pub(super) input_id: Option<String>,
    #[serde(rename = "type")]
    #[cfg_attr(
        not(test),
        expect(
            dead_code,
            reason = "Preserves the complete mounted recorder key schema"
        )
    )]
    key_type: String,
    pub(super) scancode: u32,
    #[serde(rename = "virtualKey")]
    #[cfg_attr(
        not(test),
        expect(
            dead_code,
            reason = "Capture uses keyCode; the source virtualKey is retained separately"
        )
    )]
    virtual_key: String,
    #[serde(rename = "keyCode")]
    pub(super) key_code: String,
    pub(super) flag: u32,
    #[serde(rename = "outputFlag")]
    pub(super) output_flag: Option<u32>,
    #[serde(rename = "pageID")]
    #[cfg_attr(
        not(test),
        expect(dead_code, reason = "Preserves optional source HID page metadata")
    )]
    page_id: Option<String>,
    #[serde(rename = "HID")]
    #[cfg_attr(
        not(test),
        expect(dead_code, reason = "Preserves optional source HID usage metadata")
    )]
    hid: Option<String>,
    #[cfg_attr(
        not(test),
        expect(dead_code, reason = "Preserves the source modifier annotation")
    )]
    modifier: Option<String>,
    #[serde(rename = "ExtendedKey")]
    #[cfg_attr(
        not(test),
        expect(dead_code, reason = "Preserves the source extended key annotation")
    )]
    extended_key: Option<String>,
}

pub(super) fn keys() -> &'static [CaptureKey] {
    static KEYS: OnceLock<Vec<CaptureKey>> = OnceLock::new();
    KEYS.get_or_init(make_shortcut_capture_keys_table)
}

/// Module 26061 DKMKEYS belongs to product 708, BLE 707 and receiver 706.
/// The source tests truthiness before replacing the native scan code.
pub(super) fn dkm_scan_code(key: u32) -> Option<u32> {
    match key {
        251 => Some(14),
        252 => Some(48),
        253 => Some(57),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mounted_capture_table_keeps_source_order_and_compiler_differences() {
        let rows = keys();
        assert_eq!(rows.len(), 144);
        assert_eq!(rows[0].input_id.as_deref(), Some("KEY_A"));
        let by_id = |id| {
            rows.iter()
                .find(|row| row.input_id.as_deref() == Some(id))
                .unwrap()
        };
        assert_eq!(by_id("KEY_RIGHT_CTRL").output_flag, None);
        assert_eq!(by_id("KEY_RIGHT_ALT").output_flag, None);
        assert_eq!(by_id("KEY_NUMPAD_PERIOD").virtual_key, "46");
        assert_eq!(by_id("KEY_CANCEL").name, "Invalid/cancel");
        assert_eq!(by_id("KEY_CANCEL").key_type, "");
        assert_eq!(by_id("KEY_NUMPAD_NUM_LOCK").key_type, "Numpad");
        assert_eq!(
            rows.iter()
                .enumerate()
                .filter(|(_, row)| row.input_id.as_deref() == Some("KEY_NUMPAD_NUM_LOCK"))
                .map(|(ix, row)| (ix, row.key_type.as_str()))
                .collect::<Vec<_>>(),
            [(60, "Numpad"), (105, "Modifiers")]
        );
        assert_eq!(by_id("KEY_F13").page_id, None);
        assert_eq!(by_id("KEY_F13").hid, None);
        assert!(rows.iter().any(|row| row.input_id.is_none()
            && row.name == "<"
            && row.hid.as_deref() == Some("100")));
        assert!(
            rows.iter()
                .all(|row| row.modifier.as_deref().is_none_or(|value| value == "16"))
        );
        assert!(rows.iter().all(|row| {
            row.extended_key
                .as_deref()
                .is_none_or(|value| value == "Extended_00")
        }));
        assert!(!rows.iter().any(|row| {
            row.input_id
                .as_deref()
                .is_some_and(|id| id.starts_with("DPAD_"))
        }));
    }

    #[test]
    fn dkm_redirect_preserves_only_source_defined_keys() {
        assert_eq!(dkm_scan_code(251), Some(14));
        assert_eq!(dkm_scan_code(252), Some(48));
        assert_eq!(dkm_scan_code(253), Some(57));
        for key in [0, 1, 10, 11, 32, 65, 84, 96, 247, 250, 254] {
            assert_eq!(dkm_scan_code(key), None);
        }
    }
}

