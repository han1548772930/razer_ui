/// `getDefaultActuation` selects per-key preset exceptions only when a key is
/// supplied; the global Rapid Trigger task deliberately requests the common row.
pub(super) fn actuation(guid: &str, input: Option<&str>) -> ActuationDefaults {
    let special = matches!(guid, FPS | ANALOG_WASD | RACING | HIGH)
        && input.is_some_and(|input| {
            matches!(
                input,
                "KEY_CAPS_LOCK"
                    | "KEY_INSERT"
                    | "KEY_DELETE"
                    | "KEY_PAGE_UP"
                    | "KEY_HOME"
                    | "KEY_END"
                    | "KEY_PAGE_DOWN"
            )
        });
    if guid == FACTORY || special {
        ActuationDefaults {
            low: 32760,
            high: 31122,
        }
    } else if matches!(guid, HIGH | GENERAL) {
        ActuationDefaults {
            low: 13104,
            high: 11466,
        }
    } else {
        ActuationDefaults {
            low: 19656,
            high: 18018,
        }
    }
}

pub(super) fn rapid(guid: &str, input: Option<&str>) -> RapidDefaults {
    if guid == FACTORY {
        RapidDefaults {
            enabled: true,
            down: 6552,
            up: 6552,
        }
    } else if matches!(guid, FPS | HIGH) {
        RapidDefaults {
            enabled: input
                .is_some_and(|input| matches!(input, "KEY_A" | "KEY_W" | "KEY_S" | "KEY_D")),
            down: 4914,
            up: 4914,
        }
    } else if matches!(guid, ANALOG_WASD | RACING | GENERAL) {
        RapidDefaults {
            enabled: false,
            down: 6552,
            up: 6552,
        }
    } else {
        RapidDefaults {
            enabled: false,
            down: 1638,
            up: 1638,
        }
    }
}

