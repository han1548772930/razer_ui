#[derive(Clone, Copy, Debug)]
pub(super) enum DefaultOutput {
    Keyboard(&'static str),
    PrintScreen,
    Media {
        action: &'static str,
        turbo: bool,
    },
    System(&'static str),
    Backlight(&'static str),
    Profile {
        action: &'static str,
        guid: Option<&'static str>,
    },
    Otfm,
    GameMode,
    SnapTap,
}

#[derive(Clone, Copy, Debug)]
pub(super) struct DefaultMapping {
    pub input: &'static str,
    pub output: DefaultOutput,
}
impl DefaultMapping {
    pub fn record(self) -> Value {
        let mut row = json!({"inputID":self.input,"inputType":"KeyInput","isHyperShift":true});
        let (kind, group) = match self.output {
            DefaultOutput::Keyboard(key) => ("keyboardGroup", Some(json!({"key":key}))),
            DefaultOutput::PrintScreen => (
                "keyboardGroup",
                Some(json!({"key":"KEY_PRINT_SCREEN","keyAssignment":"Prnt Scrn","modifiers":[]})),
            ),
            DefaultOutput::Media { action, turbo } => {
                let mut group = json!({"multimediaAssignment":action});
                if turbo {
                    group["useTurbo"] = json!(true);
                }
                ("multimediaGroup", Some(group))
            }
            DefaultOutput::System(action) => {
                ("systemGroup", Some(json!({"systemAssignment":action})))
            }
            DefaultOutput::Backlight(action) => (
                "backlightGroup",
                Some(json!({"backlightAssignment":action})),
            ),
            DefaultOutput::Profile { action, guid } => {
                let mut group = json!({"profileNavigationAssignment":action});
                if let Some(guid) = guid {
                    group["guid"] = json!(guid);
                }
                ("profileNavigationGroup", Some(group))
            }
            DefaultOutput::Otfm => ("otfmGroup", None),
            DefaultOutput::GameMode => ("gameModeGroup", None),
            DefaultOutput::SnapTap => ("snapTapGroup", Some(json!({"snapTapAssignment":"toggle"}))),
        };
        row["outputType"] = json!(kind);
        if let Some(group) = group {
            row[kind] = group;
        }
        row
    }
}

