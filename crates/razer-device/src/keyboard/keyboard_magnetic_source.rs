pub(super) fn obm_keys(product: u32, layout: u32) -> anyhow::Result<Vec<FirmwareKey>> {
    let inputs = match product {
        740 if layout == 12 => BUTTONS_740_JP,
        740 if [3, 4, 6, 7, 10, 15, 16, 17, 18].contains(&layout) => BUTTONS_740_UK,
        740 => BUTTONS_740,
        746 => BUTTONS_746,
        _ => anyhow::bail!("Magnetic OBM product differs"),
    };
    let firmware = firmware_keys(product)?;
    let mut keys = std::collections::BTreeMap::new();
    for input in inputs {
        if let Some(key) = firmware.iter().find(|key| key.input == *input) {
            keys.entry(key.id).or_insert(*key);
        }
    }
    ensure!(!keys.is_empty(), "Magnetic OBM key identities are absent");
    Ok(keys.into_values().collect())
}

#[derive(Clone, Copy, Debug)]
struct FullInput {
    input: &'static str,
    analog: bool,
    hypershift: bool,
}

pub(super) fn full_mapping_list(product: u32) -> anyhow::Result<Vec<Value>> {
    let inputs = match product {
        740 => FULL_740,
        746 => FULL_746,
        _ => anyhow::bail!("Magnetic full mapping product differs"),
    };
    Ok(inputs.iter().map(|input|json!({"inputID":input.input,"inputType":if input.analog {"AnalogInput"} else {"KeyInput"},"isHyperShift":input.hypershift,"outputType":"disableGroup","disableGroup":{"disableAssignment":"Disable"}})).collect())
}

pub(super) fn firmware_key(product: u32, input: &str) -> anyhow::Result<u8> {
    firmware_keys(product)?
        .iter()
        .find(|key| key.input == input)
        .map(|key| key.id)
        .context("Magnetic key has no firmware identity")
}

