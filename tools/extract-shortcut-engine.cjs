// Static AST extraction only. No source bundle is evaluated or loaded.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const acorn = require('acorn');

const root = path.resolve(__dirname, '..');
const input = '.ref/applications/synapse/dashboard/static/js/2280.4d9e22ab.chunk.js';
const folder = '.ref/applications/synapse/dashboard/';
const manifest = JSON.parse(fs.readFileSync(path.join(root, folder, 'asset-manifest.json'), 'utf8'));
if (!Object.values(manifest.files).some(name => folder + name.replace(/^\.\//, '') === input)) {
  throw Error('Keyboard source is not declared by the current Dashboard manifest');
}
const output = path.join(root, 'crates/razer-pages/src/features/shortcut_engine_keys.rs');
const source = fs.readFileSync(path.join(root, input), 'utf8');
const ast = acorn.parse(source, { ecmaVersion: 'latest' });
let keyModule;
function walk(node) {
  if (!node || typeof node !== 'object') return;
  if (node.type === 'Property' && node.key?.value === 629) keyModule = node.value;
  for (const value of Object.values(node)) {
    if (Array.isArray(value)) value.forEach(walk);
    else if (value && typeof value === 'object') walk(value);
  }
}
walk(ast);
if (!keyModule) throw new Error('Original keyboard module 629 not found');
const declaration = keyModule.body.body.find(node => node.type === 'VariableDeclaration');
const array = declaration?.declarations.find(node => node.init?.type === 'ArrayExpression')?.init;
if (!array) throw new Error('Original keyboard array not found');
function literal(node) {
  if (node.type === 'Literal') return node.value;
  if (node.type === 'CallExpression' && node.callee.name === 'parseInt'
      && node.arguments.length === 2 && node.arguments.every(arg => arg.type === 'Literal')) {
    return parseInt(node.arguments[0].value, node.arguments[1].value);
  }
  throw new Error(`Unsupported static value ${node.type}`);
}
const ids = new Set();
const rows = array.elements.map(node => Object.fromEntries(node.properties.map(property =>
  [property.key.name ?? property.key.value, literal(property.value)])))
  .filter(row => row.inputID && row.scancode > 0)
  .map(row => {
    if (ids.has(row.inputID)) throw new Error(`Duplicate input ${row.inputID}`);
    ids.add(row.inputID);
    return `    (${JSON.stringify(row.inputID)}, ${row.scancode}, ${row.outputFlag ?? row.flag}),`;
  });
const digest = crypto.createHash('sha256').update(source).digest('hex');
const text = `// Generated by tools/extract-shortcut-engine.cjs; do not edit.\n`
  + `// ${input}, module 629.\n// Source SHA-256: ${digest}\n`
  + `// (inputID, scancode, outputFlag ?? flag); zero-scan diagonal inputs are excluded.\n&[\n`
  + rows.join('\n') + '\n]\n';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(output, 'utf8').replace(/\r\n/g, '\n') !== text) {
    throw new Error('shortcut_engine_keys.rs differs from the original source');
  }
} else fs.writeFileSync(output, text, 'utf8');
console.log(`Extracted ${rows.length} original keyboard input records.`);
